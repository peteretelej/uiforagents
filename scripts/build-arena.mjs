// Generates the arena: a self-contained catalog page rendering the sample UI
// and every item example across the example themes, plus themes/tokens.css
// (the theme token sets, cascade-layered, for standalone examples). Enforces
// the pinned fg/bg contrast pairs via scripts/lib/color.mjs before writing;
// all theme CSS is serialized through the shared scripts/lib/themes-css.mjs.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadKit, readText } from "./lib/items.mjs";
import { tokenPairRatio } from "./lib/color.mjs";
import { themesCss, themesLayerStyle } from "./lib/themes-css.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const { themes, items } = await loadKit();
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));

// Pinned fg/bg pairs: text pairs at 4.5:1, foreground-on-accent and
// status/accent-on-soft pairs at the 3.0:1 WCAG large-text/UI threshold.
const CONTRAST_PAIRS = [
  { min: 4.5, pairs: [
    ["--uifa-text", "--uifa-bg"],
    ["--uifa-text", "--uifa-surface"],
    ["--uifa-text", "--uifa-surface-2"],
    ["--uifa-text-muted", "--uifa-bg"],
    ["--uifa-text-muted", "--uifa-surface"],
  ] },
  { min: 3, pairs: [
    ["--uifa-accent-fg", "--uifa-accent"],
    ["--uifa-ok-fg", "--uifa-ok"],
    ["--uifa-warn-fg", "--uifa-warn"],
    ["--uifa-danger-fg", "--uifa-danger"],
    ["--uifa-accent", "--uifa-bg"],
    ["--uifa-accent", "--uifa-surface"],
    ["--uifa-accent", "--uifa-accent-soft"],
    ["--uifa-ok", "--uifa-ok-soft"],
    ["--uifa-warn", "--uifa-warn-soft"],
    ["--uifa-danger", "--uifa-danger-soft"],
  ] },
];

const contrastFailures = [];
for (const theme of themes) {
  for (const { min, pairs } of CONTRAST_PAIRS) {
    for (const [fg, bg] of pairs) {
      const ratio = tokenPairRatio(theme.tokens, fg, bg);
      if (ratio < min) contrastFailures.push(`${theme.slug}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1 (minimum ${min}:1)`);
    }
  }
}
if (contrastFailures.length > 0) {
  console.error(`build-arena: contrast validation failed\n${contrastFailures.join("\n")}`);
  process.exit(1);
}

// themes/tokens.css: the theme contract as cascade-layered CSS, keyed by
// [data-theme]; the first theme also owns :root.
const tokensCss = themesCss({
  themes,
  header: `/* GENERATED by scripts/build-arena.mjs from themes/index.mjs - uiforagents ${version} - do not edit. */`,
});
writeFileSync(join(ROOT, "themes", "tokens.css"), tokensCss);

// Collect each item's example markup and scripts.
const itemBlocks = items.map((item) => {
  const css = item.manifest.files
    .filter((f) => f.type === "kit:style")
    .map((f) => readText(join(item.dir, f.path)).trim())
    .join("\n\n");
  const behaviorFiles = new Map(
    item.manifest.files
      .filter((f) => f.type === "kit:behavior")
      .map((f) => [f.path, readText(join(item.dir, f.path)).trim()])
  );
  const examplePath = item.manifest.files.find((f) => f.type === "kit:example").path;
  const example = readText(join(item.dir, examplePath));
  const bodyMatch = example.match(/<body[^>]*>([\s\S]*)<\/body>/);
  if (!bodyMatch) throw new Error(`items/${item.name}: example has no <body> to extract`);
  const body = bodyMatch[1].replace(/<script src="([^"]+)"><\/script>/g, (tag, src) => {
    const content = behaviorFiles.get(src);
    if (content === undefined) {
      throw new Error(`items/${item.name}: example references "${src}" which is not a declared kit:behavior file`);
    }
    return `<script>\n${content}\n</script>`;
  });
  return { name: item.name, css, body };
});

