function directionDocument(direction) {
  const itemsHtml = itemBlocks
    .map(({ name, body }) => `<section class="arena-item"><h3>${name}</h3>\n${body}\n</section>`)
    .join("\n");
  return `<!doctype html>
<html lang="en" data-theme="${direction.slug}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
${directions.map((d, i) => {
  const selector = i === 0 ? [":root", `[data-theme="${d.slug}"]`] : [`[data-theme="${d.slug}"]`];
  const body = Object.entries(d.tokens).map(([t, v]) => `  ${t}: ${v};`).join("\n");
  return `${selector.join(",\n")} {\n${body}\n}`;
}).join("\n")}
</style>
<style>${itemBlocks.map((b) => b.css).join("\n\n")}</style>
<style>${iframeChrome}</style>
</head>
<body>
${sampleUi}
${itemsHtml}
</body>
</html>`;
}

const pages = directions.map((direction) => ({
  slug: direction.slug,
  name: direction.name,
  mood: direction.mood,
  notes: direction.notes,
  html: directionDocument(direction),
}));

const payload = JSON.stringify({ pages }).replace(/<\//g, "<\\/");

