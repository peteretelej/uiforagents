// Generates the arena: a self-contained catalog page rendering the sample UI
// and every item example across the example directions, plus themes/tokens.css
// (the direction token sets as plain CSS for standalone examples).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadKit } from "./lib/items.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const { directions, items } = await loadKit();

// themes/tokens.css: the base scale as CSS, keyed by [data-theme].
const tokensCss = [
  "/* GENERATED by scripts/build-arena.mjs from themes/directions.mjs - do not edit. */",
  ...directions.map((direction, index) => {
    const selector = index === 0 ? [":root", `[data-theme="${direction.slug}"]`] : [`[data-theme="${direction.slug}"]`];
    const body = Object.entries(direction.tokens)
      .map(([token, value]) => (token === "color-scheme" ? `  ${token}: ${value};` : `  ${token}: ${value};`))
      .join("\n");
    return `${selector.join(",\n")} {\n${body}\n}`;
  }),
].join("\n\n") + "\n";
writeFileSync(join(ROOT, "themes", "tokens.css"), tokensCss);

// Collect each item's example markup and scripts.
const itemBlocks = items.map((item) => {
  const css = item.manifest.files
    .filter((f) => f.type === "kit:style")
    .map((f) => readFileSync(join(item.dir, f.path), "utf8").trim())
    .join("\n\n");
  const behaviorFiles = new Map(
    item.manifest.files
      .filter((f) => f.type === "kit:behavior")
      .map((f) => [f.path, readFileSync(join(item.dir, f.path), "utf8").trim()])
  );
  const examplePath = item.manifest.files.find((f) => f.type === "kit:example").path;
  const example = readFileSync(join(item.dir, examplePath), "utf8");
  const bodyMatch = example.match(/<body[^>]*>([\s\S]*)<\/body>/);
  if (!bodyMatch) throw new Error(`items/${item.name}: example has no <body> to extract`);
  const body = bodyMatch[1].replace(/<script src="([^"]+)"><\/script>/g, (tag, src) => {
    const content = behaviorFiles.get(src);
    if (content === undefined) {
      throw new Error(`items/${item.name}: example references "${src}" which is not a declared kit:behavior file`);
    }
    return `<script>\n${content}\n</script>`;
  });
  return { name: item.name, css, body };
});

