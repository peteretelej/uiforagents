// Theme-scoped arena presentation, not kit artifacts: the glass dialect is
// load-bearing on a colorful backdrop behind its frosted panels, so its page
// paints one. Stops stay deep and semi-transparent so the backdrop's
// luminance band stays near --uifa-bg and the contrast-validated glass pairs
// hold over the glow cores.
const arenaChromeExtras = {
  glass: `
  html[data-theme="glass"] body {
    background:
      radial-gradient(52% 44% at 12% 8%, oklch(35% 0.16 335 / 0.5), transparent 70%),
      radial-gradient(48% 42% at 88% 12%, oklch(34% 0.13 250 / 0.45), transparent 70%),
      radial-gradient(60% 50% at 50% 100%, oklch(34% 0.12 175 / 0.4), transparent 72%),
      var(--uifa-bg);
    background-attachment: fixed;
  }
`,
};

function themeDocument(theme) {
  const itemsHtml = itemBlocks
    .map(({ name, body }) => `<section class="arena-item"><h3>${name}</h3>\n${body}\n</section>`)
    .join("\n");
  const chromeExtra = arenaChromeExtras[theme.slug] ?? "";
  return `<!doctype html>
<html lang="en" data-theme="${theme.slug}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
${themesLayerStyle(themes)}
</style>
<style>${itemBlocks.map((b) => b.css).join("\n\n")}</style>
<style>${iframeChrome}</style>
<style>${chromeExtra}</style>
</head>
<body>
${sampleUi}
${itemsHtml}
</body>
</html>`;
}

const pages = themes.map((theme) => ({
  slug: theme.slug,
  name: theme.name,
  mood: theme.mood,
  notes: theme.notes,
  html: themeDocument(theme),
}));

const payload = JSON.stringify({ pages }).replace(/<\//g, "<\\/");

